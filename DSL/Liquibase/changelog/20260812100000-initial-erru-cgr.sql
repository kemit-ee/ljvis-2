    handler_name                    VARCHAR(200),
    error_message                   TEXT,
    -- ── Audit ───────────────────────────────────────────────
    created_at                      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by                      VARCHAR(100)    NOT NULL DEFAULT 'system',
    CONSTRAINT pk_cgr_request PRIMARY KEY (id)
