    tm_family_name                  VARCHAR(100),
    tm_date_of_birth                DATE,
    tm_place_of_birth               VARCHAR(200),
    tm_first_name_search_key        VARCHAR(20),
    tm_family_name_search_key       VARCHAR(20),
    -- ── Searched transport manager — certificate (7B, choice) ──
