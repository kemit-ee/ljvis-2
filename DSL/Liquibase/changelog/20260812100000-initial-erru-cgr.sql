ALTER TABLE erru.cgr_request
    ADD CONSTRAINT chk_cgr_direction CHECK (direction IN ('outgoing', 'incoming')),
    ADD CONSTRAINT chk_cgr_status CHECK (status IN ('initiated', 'sent', 'received', 'answered', 'error')),
    ADD CONSTRAINT chk_cgr_status_matches_direction CHECK (
        status = 'error'
        OR (direction = 'outgoing' AND status IN ('initiated', 'sent'))
        OR (direction = 'incoming' AND status IN ('received', 'answered'))
    ),
    ADD CONSTRAINT chk_cgr_business_case_id_not_blank CHECK (btrim(business_case_id) <> ''),
    ADD CONSTRAINT chk_cgr_version_positive CHECK (version >= 1),
    ADD CONSTRAINT chk_cgr_cgr_to_format CHECK (cgr_to IS NULL OR cgr_to ~ '^[A-Z]{2}$'),
    ADD CONSTRAINT chk_cgr_search_choice CHECK (
        (
            COALESCE(btrim(tm_family_name), '') <> ''
            AND COALESCE(btrim(tm_first_name), '') <> ''
            AND tm_date_of_birth IS NOT NULL
        )
        OR
        (
            COALESCE(btrim(certificate_number), '') <> ''
            AND certificate_issue_date IS NOT NULL
            AND COALESCE(btrim(certificate_issue_country), '') <> ''
        )
    );

COMMENT ON CONSTRAINT chk_cgr_status_matches_direction ON erru.cgr_request IS 'Keeps the two status chains from leaking into each other: an outgoing request can never be received/answered and an incoming one can never be initiated/sent. error is shared by both directions.';
COMMENT ON CONSTRAINT chk_cgr_search_choice ON erru.cgr_request IS 'ERRU CGR is an XSD choice: SearchedTransportManager carries either a complete TransportManagerNameDetails (family name + first name + date of birth) or a complete TransportManagerCertificateDetails (certificate number + issue date + issue country), or both. Enforced in the database as defence in depth; the user-facing check lives in TEMPLATES/erru/cgr/validate-cgr-request.yml and applies to inbound requests too.';

CREATE UNIQUE INDEX uq_cgr_inbound_technical_id
    ON erru.cgr_request (technical_id)
    WHERE direction = 'incoming' AND status = 'received';

COMMENT ON INDEX erru.uq_cgr_inbound_technical_id IS 'Inbound idempotency. Partial index: technical_id repeats across later snapshots of the same message (answered, error), but there can be exactly one received row per technical_id. A redelivered ERRU message therefore cannot create a duplicate request. Heartbeat probes never reach this index because they are never persisted (see append-cgr-inbound.sql).';
