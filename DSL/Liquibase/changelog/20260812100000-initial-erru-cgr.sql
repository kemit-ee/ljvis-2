    -- ── Request body (globalBodyRequestType) ────────────────
    originating_authority           VARCHAR(50),
    request_source                  VARCHAR(30),
    request_purpose                 VARCHAR(30),
    -- ── Searched transport manager — name (7A, choice) ──────
